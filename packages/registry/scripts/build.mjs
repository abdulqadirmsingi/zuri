// Renders registry.json (with __REGISTRY_URL__ placeholders) and runs `shadcn build`.
// Why: registryDependencies must be absolute URLs, so the site's address is written in at build time.
import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolveRegistryUrl } from "./registry-url.mjs";

const base = resolveRegistryUrl();
const out = process.env.ZURI_REGISTRY_OUT ?? "../../apps/web/.registry";
const rendered = "registry.generated.json";

writeFileSync(
  rendered,
  readFileSync("registry.json", "utf8").replaceAll("__REGISTRY_URL__", `${base}/r`),
);
const res = spawnSync("pnpm", ["exec", "shadcn", "build", rendered, "-o", out], {
  stdio: "inherit",
});
rmSync(rendered, { force: true });
if (res.status !== 0) process.exit(res.status ?? 1);

// Lazy JSON imports instead of runtime fs reads: statically traceable and edge-friendly.
const entries = readdirSync(out)
  .filter((f) => f.endsWith(".json"))
  .map((f) => [f === "registry.json" ? "index" : f.slice(0, -5), f]);
const lines = entries.map(
  ([n, f]) => `  ${JSON.stringify(n)}: () => import(${JSON.stringify(`./${f}`)}),`,
);
writeFileSync(
  `${out}/manifest.ts`,
  `// Generated by packages/registry/scripts/build.mjs. Do not edit.\nexport const loaders = {\n${lines.join("\n")}\n};\n`,
);
